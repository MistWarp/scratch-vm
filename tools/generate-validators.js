// Precompiles the project schema validators so loading a project does not build them with ajv at runtime.
// Run after updating scratch-parser: node tools/generate-validators.js
const fs = require('fs');
const path = require('path');
const Ajv = require('ajv');
const pack = require('ajv-pack');
const terser = require('terser');
const {SCHEMAS, prepareAjv} = require('../src/serialization/validator-schemas');

const OUTPUT = path.resolve(__dirname, '../src/serialization/validators');
fs.mkdirSync(OUTPUT, {recursive: true});

for (const [name, {schema, sb2}] of Object.entries(SCHEMAS)) {
    const ajv = prepareAjv(new Ajv({sourceCode: true, meta: false, validateSchema: false}), sb2);
    // Minified: the module's source stays in memory once loaded. No compress pass, so the logic is unchanged.
    const minified = terser.minify(pack(ajv, ajv.compile(schema())), {compress: false, mangle: true});
    if (minified.error) throw minified.error;
    const code = minified.code;
    fs.writeFileSync(
        path.join(OUTPUT, `${name}.generated.js`),
        '/* eslint-disable */\n' +
            `// Generated by tools/generate-validators.js from scratch-parser's ${name} schema.\n${code}`
    );
    console.log(`wrote ${name}.generated.js`);
}
